    private void addAccountButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addAccountButtonActionPerformed
    try {
            int customerId = readInt(customerIdField, "Customer ID");

            if (customerDAO.getCustomerById(customerId) == null) {
                showError("Customer not found.");
                return;
            }

            BigDecimal initialBalance = readAmount(initialBalanceField, "Initial balance");
            Account account = new Account(
                    0,
                    requiredText(accountTypeField, "Account type"),
                    initialBalance,
                    customerId);

            int accountId = accountDAO.addAccount(account);

            if (initialBalance.compareTo(BigDecimal.ZERO) > 0) {
                transactionDAO.addTransaction(new Transaction(0, accountId, "Initial Deposit", initialBalance, null));
            }

            outputArea.setText("Account added successfully.\nAccount ID: " + accountId);
            clearAccountFields();
        } catch (IllegalArgumentException | SQLException ex) {
            showError(ex.getMessage());
        }      
    }//GEN-LAST:event_addAccountButtonActionPerformed

