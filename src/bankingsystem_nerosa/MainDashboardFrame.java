    private void addAccountButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addAccountButton1ActionPerformed
    try {
            int customerId = readInt(customerIdField, "Customer ID");
            Customer customer = customerDAO.getCustomerById(customerId);

            if (customer == null) {
                showError("Customer not found.");
                return;
            }

            List<Account> accounts = accountDAO.getAccountsByCustomerId(customerId);
            StringBuilder builder = new StringBuilder();
            builder.append(customer).append("\n\n");

            if (accounts.isEmpty()) {
                builder.append("No accounts found for this customer.");
            } else {
                for (Account account : accounts) {
                    builder.append(account).append("\n");
                }
            }

            outputArea.setText(builder.toString());
        } catch (IllegalArgumentException | SQLException ex) {
            showError(ex.getMessage());
        }    
    }//GEN-LAST:event_addAccountButton1ActionPerformed

